"use strict";

// Для каждого выражения сначала записано предсказание, затем выводится
// фактическое значение и тип результата.

// 1. Предсказание: "82", string — число приводится к строке при конкатенации.
console.log('1) "8" + 2 =', "8" + 2, "| тип:", typeof ("8" + 2));

// 2. Предсказание: 6, number — минус не определён для строк, идёт числовое приведение.
console.log('2) "8" - 2 =', "8" - 2, "| тип:", typeof ("8" - 2));

// 3. Предсказание: 10, number — явное преобразование до сложения.
console.log('3) Number("8") + 2 =', Number("8") + 2, "| тип:", typeof (Number("8") + 2));

// 4. Предсказание: false, boolean — сравнение строк посимвольно, "1" < "3".
console.log('4) "12" > "3" =', "12" > "3", "| тип:", typeof ("12" > "3"));

// 5. Предсказание: false, boolean — строгое сравнение не приводит типы.
console.log('5) 12 === "12" =', 12 === "12", "| тип:", typeof (12 === "12"));

// 6. Предсказание: 0, number — пустая строка превращается в ноль.
console.log('6) Number("") =', Number(""), "| тип:", typeof Number(""));

// 7. Предсказание: NaN, number — строку без числа привести нельзя.
console.log('7) Number("text") =', Number("text"), "| тип:", typeof Number("text"));

// 8. Предсказание: true, boolean — любая непустая строка истинна.
console.log('8) Boolean("false") =', Boolean("false"), "| тип:", typeof Boolean("false"));

// 9. Предсказание: "object", string — известная особенность языка.
console.log('9) typeof null =', typeof null, "| тип самого результата:", typeof (typeof null));

// 10. Предсказание: "number", string — NaN относится к числовому типу.
console.log('10) typeof NaN =', typeof NaN, "| тип самого результата:", typeof (typeof NaN));
