-- Запуск в новой пустой БД tip_tasks от владельца tip_app:
-- psql ... -v ON_ERROR_STOP=1 -1 -f sql/01_schema.sql
-- Без DROP, IF NOT EXISTS и COMMIT: повтор в заполненной базе должен падать.

CREATE TABLE public.categories (
  id   integer GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  CONSTRAINT categories_pkey PRIMARY KEY (id),
  CONSTRAINT categories_id_positive CHECK (id > 0),
  CONSTRAINT categories_name_key UNIQUE (name),
  CONSTRAINT categories_name_length CHECK (char_length(name) BETWEEN 1 AND 100),
  CONSTRAINT categories_name_trimmed CHECK (name = btrim(name))
);

CREATE TABLE public.tasks (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  title       text    NOT NULL,
  completed   boolean NOT NULL DEFAULT false,
  priority    text    NOT NULL,
  category_id integer NOT NULL,
  CONSTRAINT tasks_pkey PRIMARY KEY (id),
  CONSTRAINT tasks_id_positive CHECK (id > 0),
  CONSTRAINT tasks_title_length CHECK (char_length(title) BETWEEN 1 AND 100),
  CONSTRAINT tasks_title_trimmed CHECK (title = btrim(title)),
  CONSTRAINT tasks_priority_allowed CHECK (priority IN ('low', 'medium', 'high')),
  -- RESTRICT: категорию с задачами удалить нельзя, пустую можно
  CONSTRAINT tasks_category_id_fkey FOREIGN KEY (category_id)
    REFERENCES public.categories (id) ON DELETE RESTRICT
);

-- Внешний ключ не создаёт индекс на ссылающейся колонке сам
CREATE INDEX tasks_category_id_idx ON public.tasks (category_id);
